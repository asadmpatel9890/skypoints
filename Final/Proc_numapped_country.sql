CREATE OR REPLACE PROCEDURE UNMAPPED_COUNTIRES()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
  INSERT INTO SKYPOINTS_DEV.FINAL_STAGE.TABLE_UNMAPPED_COUNTRY
    (NAME, MEM_ID, ENROLL_DT, FLIGHT_DT, TIER, AGENT_NAME, STATE,
     COUNTRY, DOB, AGE, STALE_MEMBERS, FLAG, CURR_DATE)
  SELECT d.NAME, d.MEM_ID, d.ENROLL_DT, d.FLIGHT_DT, d.TIER, d.AGENT_NAME, d.STATE,
         d.COUNTRY, d.DOB, d.AGE, d.STALE_MEMBERS, d.FLAG, d.CURR_DATE
  FROM SKYPOINTS_DEV.TRANSFORMATION_STAGE.COUNTRY_MEMBERS_LATEST d   -- fix C: same source
  WHERE NOT EXISTS (
    SELECT 1
    FROM SKYPOINTS_DEV.FINAL_STAGE.COUNTRY_TABLE_MAP m
    WHERE m.COUNTRY_CODE = UPPER(TRIM(d.COUNTRY))
      AND m.IS_ACTIVE
  );

  RETURN 'Unmapped rows inserted: ' || SQLROWCOUNT;
END;
$$;