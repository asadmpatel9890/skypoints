use schema SKYPOINTS_DEV.FINAL_STAGE;

create or replace table SKYPOINTS_DEV.FINAL_STAGE.country_table_template
(
    NAME           VARCHAR(255) NOT NULL,
	MEM_ID         VARCHAR(18) NOT NULL,
	ENROLL_DT      DATE NOT NULL,
	FLIGHT_DT      DATE,
	TIER           VARCHAR(5),
	AGENT_NAME     VARCHAR(255),
	STATE          VARCHAR(5),
	COUNTRY        VARCHAR(5),
	DOB            DATE,
	AGE            NUMBER(38,0),
	STALE_MEMBERS  VARCHAR(1),
	FLAG           VARCHAR(1),
	CURR_DATE      DATE,
	constraint PK_MEMBER_INTERMEDIATE primary key (MEM_ID)
);

CREATE TABLE IF NOT EXISTS SKYPOINTS_DEV.FINAL_STAGE.TABLE_USA          LIKE SKYPOINTS_DEV.FINAL_STAGE.country_table_template;
CREATE TABLE IF NOT EXISTS SKYPOINTS_DEV.FINAL_STAGE.TABLE_INDIA        LIKE SKYPOINTS_DEV.FINAL_STAGE.country_table_template;
CREATE TABLE IF NOT EXISTS SKYPOINTS_DEV.FINAL_STAGE.TABLE_PHILIPPINES  LIKE SKYPOINTS_DEV.FINAL_STAGE.country_table_template;
CREATE TABLE IF NOT EXISTS SKYPOINTS_DEV.FINAL_STAGE.TABLE_CANADA       LIKE SKYPOINTS_DEV.FINAL_STAGE.country_table_template;
CREATE TABLE IF NOT EXISTS SKYPOINTS_DEV.FINAL_STAGE.TABLE_AUSTRALIA    LIKE SKYPOINTS_DEV.FINAL_STAGE.country_table_template;

-- Catch-all for missing or unknown country codes, so no member is silently dropped
CREATE TABLE IF NOT EXISTS SKYPOINTS_DEV.FINAL_STAGE.TABLE_UNMAPPED_COUNTRY LIKE SKYPOINTS_DEV.FINAL_STAGE.country_table_template;